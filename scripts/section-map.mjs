#!/usr/bin/env node
// The section map at the top of each big single-file page: its `// ===== Title =====` headers in order, so a
// reader finds the wiring, the rules and the display without scrolling 7,000 to 12,000 lines. Guards: a
// hand-kept map rots silently (the 2026-08-15 Simulation STATE.md headings contradicted their own bodies).
// Titles only, no line numbers, so ordinary edits never stale it; adding, removing or renaming a section does.
// Runtime: under 1 s. Usage: node scripts/section-map.mjs [--write]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['hr_monitor.html', 'hrv_viewer.html'];
const BEGIN = '<!-- SECTION MAP (generated by node scripts/section-map.mjs --write; never edit by hand).';
const END = 'END SECTION MAP -->';

function titles(src) {
  return [...src.matchAll(/^\s*\/\/ (?:=====|-----) (.+?)(?: (?:=====|-----))?\s*$/gm)].map((m) => m[1].replace(/\s+/g, ' ').trim());
}
function block(ts) {
  return [BEGIN, 'Search for a title to jump to its section.', ...ts.map((t, i) => String(i + 1).padStart(2, ' ') + '. ' + t), END].join('\n');
}

const write = process.argv.includes('--write');
let bad = 0;
for (const f of FILES) {
  const p = path.join(ROOT, f);
  const raw = fs.readFileSync(p, 'utf8');
  const crlf = raw.includes('\r\n');
  const src = raw.replace(/\r\n/g, '\n');
  const want = block(titles(src));
  const b = src.indexOf(BEGIN), e = src.indexOf(END);
  const have = b >= 0 && e > b ? src.slice(b, e + END.length) : null;
  if (write) {
    let out;
    if (have) out = src.slice(0, b) + want + src.slice(e + END.length);
    else {
      // After the doctype line, before <html>, so it is the first thing a reader of the file sees.
      const nl = src.indexOf('\n');
      out = src.slice(0, nl + 1) + want + '\n' + src.slice(nl + 1);
    }
    fs.writeFileSync(p, crlf ? out.replace(/\n/g, '\r\n') : out);
    console.log(`section-map: wrote ${f} (${titles(src).length} sections)`);
  } else if (have !== want) {
    console.log(`FAIL ${f}: section map ${have ? 'is stale' : 'is missing'}; run node scripts/section-map.mjs --write`);
    bad++;
  } else console.log(`ok   ${f}: ${titles(src).length} sections`);
}
process.exit(bad ? 1 : 0);
